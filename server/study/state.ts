import { MISTAKE_LABEL, RUNG_LABEL, rungIndex } from '../../src/core/study/types';
import { pending } from './ingest';
import type { StudyService } from './service';

// STATE.md — the one-page brief every Claude session reads first. Generated from the data, so it can
// never disagree with the Study home screen. Never edit it by hand: `study state` rewrites it.

const pct = (n: number) => `${Math.round(n * 100)}%`;

export function renderState(svc: StudyService): string {
  const m = svc.model();
  const today = svc.today();
  const lines: string[] = [`# STATE — ${today}`, '', '_Generated by `study state`. Do not edit; it is rewritten nightly and after every ingest._', ''];
  if (!m.assessment) {
    lines.push('`assessment.yaml` is missing or does not parse. Fix it first (see `study status`).');
    return lines.join('\n') + '\n';
  }
  const p = svc.progress();
  const paceText =
    p.pace.status === 'no_data'
      ? 'not enough data yet'
      : `${p.pace.status === 'behind' ? `behind by ${p.pace.behindBy} concept${p.pace.behindBy === 1 ? '' : 's'}` : p.pace.status.replace('_', ' ')} (need ${p.pace.neededPerDay.toFixed(1)}/day, doing ${p.pace.averagePerDay.toFixed(1)}/day over 3 days)`;
  lines.push(
    `Semester **${m.semester}** · exam starts ${p.examStart} (in ${p.daysToExam} days) · ready by **${p.readyBy}** (in ${p.daysToReady} days)`,
    `Coverage **${pct(p.coverage)}** (released ${pct(p.releasedCoverage)}) · readiness **${pct(p.readiness)}** · IITJ track ${pct(p.iitjTrack)}`,
    `Pace: ${paceText} · projected ready: **${p.projectedReady ?? 'unknown'}**${p.reorderedByWeight ? ' · queue ordered by exam weight × weakness' : ''}`,
    `Study today: ${p.studyMinutesToday} min · total ${Math.round(p.studyMinutesTotal / 6) / 10} h`,
    '',
    '## Subjects',
    '',
    '| Subject | Concepts | Applied+ | Coverage | Released cov. | Readiness |',
    '| --- | --- | --- | --- | --- | --- |',
    ...p.subjects.map((s) => `| ${s.title} (${s.subject}) | ${s.concepts} | ${s.applied} | ${pct(s.coverage)} | ${pct(s.releasedCoverage)} | ${pct(s.readiness)} |`),
    '',
  );

  const st = svc.states();
  const weak = svc
    .concepts()
    .map((c) => ({ c, s: st.get(c.id)! }))
    .filter((x) => rungIndex(x.s.rung) >= rungIndex('seen'))
    .map((x) => {
      const vals = Object.values(x.s.mastery).filter((v): v is number => v !== null);
      return { ...x, avg: vals.length ? vals.reduce((a, b) => a + b, 0) / vals.length : 0 };
    })
    .sort((a, b) => a.avg - b.avg)
    .slice(0, 8);
  lines.push('## Weak concepts', '');
  lines.push(...(weak.length ? weak.map((w) => `- ${w.c.id} — ${w.c.title} · ${RUNG_LABEL[w.s.rung]} · mastery ${pct(w.avg)}${w.s.missedChecks ? ` · ${w.s.missedChecks} missed check(s)` : ''}`) : ['- none yet']), '');

  const repairs = svc.repairs();
  lines.push('## Open repairs', '');
  lines.push(...(repairs.length ? repairs.map((r) => `- ${r.concept} · ${MISTAKE_LABEL[r.cls]}${r.detail ? `: ${r.detail}` : ''} · ${r.count}×`) : ['- none']), '');

  const q = svc.queue(10);
  lines.push('## Next 10 in the queue', '');
  lines.push(...(q.length ? q.map((i, n) => `${n + 1}. [${i.kind}] ${'concept' in i ? `${i.concept} — ` : ''}${i.title} · ${i.why}`) : ['- the queue is empty']), '');

  const pend = pending(svc.db, svc.root);
  const errors = svc.db.fileErrors();
  const jobs = svc.jobs();
  const stubs = svc.concepts().filter((c) => c.status === 'stub').length;
  const noPath = svc.concepts().filter((c) => !m.paths.has(c.id)).length;
  const noPack = svc.concepts().filter((c) => !m.packs.has(c.id)).length;
  lines.push(
    '## Vault health',
    '',
    `- ${m.concepts.size} concept cards (${stubs} stubs) · ${noPath} without a resource path · ${noPack} without a check pack · ${m.labs.size} with a lab`,
    `- waiting for /ingest: ${pend.total} (${pend.inbox.length} in inbox, ${pend.unsorted.length} unsorted, ${pend.newAssets.length} new assets)`,
    `- files that did not parse: ${errors.length}${errors.length ? '' : ''}`,
    ...errors.slice(0, 10).map((e) => `  - ${e.path}: ${e.error}`),
    `- last jobs: ${jobs.length ? jobs.map((j) => `${j.job} ${j.ok ? 'ok' : 'FAILED'} ${new Date(j.ended).toISOString().slice(0, 16).replace('T', ' ')}`).join(' · ') : 'none yet'}`,
    '',
  );
  const open = (m.assessment.deadlines ?? []).filter((d) => !(d.submitted || svc.submittedDeadlines().has(d.id))).sort((a, b) => a.due.localeCompare(b.due));
  lines.push('## IITJ deadlines', '', ...(open.length ? open.map((d) => `- ${d.due} · ${d.subject} · ${d.title}${d.graded ? ' (graded — hints only)' : ''}`) : ['- none open']), '');
  return lines.join('\n');
}
